def cmd_check(args):
    root = ai_dir()
    errors, warnings = [], []
    all_notes = notes(root)
    copies = notes(root, conflicts=True)
    names = {m["slug"] for m in all_notes}
    slugs = {}
    for n in all_notes:
        rel = os.path.relpath(n["path"], root)
        slugs.setdefault(n["slug"], []).append(rel)
        missing = [f for f in ("type", "status", "project") if not isinstance(n["meta"].get(f), str) or not n["meta"].get(f)]
        if missing:
            warnings.append(f"{rel}: no {', '.join('`' + f + '`' for f in missing)} in its frontmatter")
        if n["text"].startswith("---\n") and n["text"].find("\n---", 4) == -1:
            warnings.append(f"{rel}: its frontmatter is not closed with `---`, so none of it is read")
        if "--" in n["slug"] and isinstance(n["meta"].get("project"), str) and n["slug"].split("--", 1)[0] != slugify(n["meta"]["project"]):
            warnings.append(f"{rel}: the file name says project {n['slug'].split('--', 1)[0]}, the frontmatter says {n['meta']['project']}")
        if SECRET.search(n["text"]):
            errors.append(f"{rel}: contains what looks like a credential. Remove it and rotate it; this folder is synced.")
        elif looks_secret(n["text"]):
            warnings.append(f"{rel}: has a value named as a password, token or key that looks generated. If it is real, remove it and rotate it.")
        if steering(n["text"]):
            warnings.append(f"{rel}: seems to direct agents or grant something. It binds nobody; show it to the user.")
        for link in re.findall(r"\[\[([^\]|#]+)", n["body"]):
            if link.strip() not in names and "--" in link:
                warnings.append(f"{rel}: links to [[{link.strip()}]], which does not exist")
        by = n["meta"].get("superseded_by")
        if n["status"] not in CLOSED and isinstance(by, str) and by:
            warnings.append(f"{rel}: has superseded_by but is still {n['status']}")
    for n in copies:
        warnings.append(f"{os.path.relpath(n['path'], root)}: looks like a copy made by a sync conflict. It is not read. The user compares it with the original and keeps one.")
    for name in sorted(os.listdir(root)):
        if re.search(r"conflict", name, re.I) and name.endswith(".md"):
            warnings.append(f"{name}: looks like a sync-conflict copy of the index. The user can delete it; the index is generated.")
    for slug, paths in slugs.items():
        if len(paths) > 1:
            errors.append(f"{slug}: the same note name in {', '.join(paths)}")
    stray = [p for p in stray_files(root) if not re.search(r"conflict", os.path.basename(p), re.I)]
    retired = sorted({p.split(os.sep)[0] for p in stray if p.split(os.sep)[0] in RETIRED_FOLDERS})
    for name in retired:
        warnings.append(f"{name}/: written by an earlier version and no longer read (personal details, progress logs and session ledgers do not belong in a synced vault). The user decides what to do with it.")
    other = [p for p in stray if p.split(os.sep)[0] not in RETIRED_FOLDERS]
    if other:
        warnings.append(f"{len(other)} Markdown file(s) are not read as notes because they are not directly inside a type folder: " + ", ".join(other[:8]) + (" ..." if len(other) > 8 else ""))
    index = os.path.join(root, INDEX_NAME)
    if os.path.isfile(index):
        current = read_file(index)
        if not is_generated(current):
            warnings.append(f"{INDEX_NAME}: kept by hand by an earlier version; it is left alone and its summaries are still used. `vault.py index --replace-legacy`, once the user agrees, generates one and keeps a copy.")
        elif current != render_index(all_notes):
            warnings.append(f"{INDEX_NAME}: out of date. Run `vault.py index`.")
    for line in errors:
        print("error: " + line)
    for line in warnings:
        print("warning: " + line)
    print(f"{len(all_notes)} notes, {len(errors)} errors, {len(warnings)} warnings.")
    return 1 if errors else 0


def cmd_init(args):
    writable()
    config = load_config()
    os.makedirs(os.path.dirname(CONFIG), exist_ok=True)
    if args.project_name or args.exclude_project:
        key = origin()[0]
        if args.exclude_project:
            config["excluded"] = sorted(set(config.get("excluded", []) + [key]))
            print(f"Recorded in {CONFIG}: nothing is read or written for {key}.")
        else:
            config.setdefault("projects", {})[key] = slugify(args.project_name)
            print(f"Recorded in {CONFIG}: {key} is the project `{slugify(args.project_name)}`.")
        atomic_write(CONFIG, json.dumps(config, indent=2) + "\n")
        return 0
    if args.no_vault:
        config.pop("vault", None)
        config["no_vault"] = True
        atomic_write(CONFIG, json.dumps(config, indent=2) + "\n")
        print(f"Recorded in {CONFIG} that no vault is used. Nothing will be read or suggested.")
        return 0
    if not args.vault:
        raise Stop("Give --vault PATH, --no-vault, --project-name NAME or --exclude-project.")
    vault = os.path.realpath(os.path.expanduser(args.vault))
    if not os.path.isdir(vault):
        raise Stop(f"{vault} is not a directory.")
    current = config.get("vault")
    if current and os.path.realpath(os.path.expanduser(current)) != vault and not args.move:
        raise Stop(f"A vault is already configured for this machine: {current}. Changing it affects every project and session. If the user asked for that, run again with --move.")
    if not os.path.isdir(os.path.join(vault, ".obsidian")):
        print(f"Note: {vault} has no .obsidian folder, so Obsidian has not opened it as a vault. Continuing anyway.")
    config["vault"] = vault
    config.pop("no_vault", None)
    atomic_write(CONFIG, json.dumps(config, indent=2) + "\n")
    print(f"Saved the vault location in {CONFIG}: {vault}")
    root = os.path.join(vault, "_ai")
    if args.scaffold:
        os.makedirs(root, exist_ok=True)
        if not os.path.isfile(os.path.join(root, INDEX_NAME)):
            write_index(root)
        print(f"Created {root}. Folders for each kind of note are made when the first note of that kind is written.")
    elif not os.path.isdir(root):
        print(f"{root} does not exist yet. Run again with --scaffold to create it, when the user wants it.")
    print("No permission settings were changed. Only this script's read-only commands are pre-approved; anything that writes asks the user as usual.")
    return 0


