#!/usr/bin/env python3
"""Mechanics for obsidian-knowledge-graph: the `_ai/` folder of notes in an Obsidian vault.

    vault.py where
    vault.py digest
    vault.py find WORD_OR_PATH... [--project NAME] [--all-projects] [--closed]
    vault.py show NOTE...
    vault.py check
    vault.py new TYPE SLUG --title T --summary S [--tags a,b] [--project NAME]
                           [--supersedes NOTE] [--said-by user|agent] [--user-asked]   (the text on standard input)
    vault.py amend NOTE --expect HASH [--replace] [--summary S] [--tags a,b]           (the text on standard input)
    vault.py close NOTE --status superseded|deprecated|wrong|revoked --reason R [--by NOTE] [--user-asked]
    vault.py index [--replace-legacy]
    vault.py init (--vault PATH [--scaffold] [--move] | --no-vault | --project-name NAME | --exclude-project)

The first five only read. The vault's location is one machine-wide setting (`init` writes
it to ~/.claude/obsidian-knowledge-graph.json; OBSIDIAN_KG_VAULT overrides it). Everything
this script reads or writes is under `<vault>/_ai/`. The index (`_ai/MANIFEST.md`) is
generated from the notes; an index kept by hand by an earlier version is left alone until
the user agrees to replace it, and then a copy is kept. Commands that write refuse under CI,
never overwrite a note they did not create in that call, never delete, and refuse text that
looks like a credential.

Standard library only.
"""
